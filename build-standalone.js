#!/usr/bin/env node
/* ============================================================================
 * 单文件版打包 —— node build-standalone.js
 * ----------------------------------------------------------------------------
 * 把 index.html 引用的 7 个 <script src> 全部内联，产出一个自包含的
 * index-standalone.html。用途只有一个：**兜底**。
 *
 * 为什么需要它：
 *   交付形态是「多文件静态站点」，这已经是最轻的形态；但只要经过第三方平台预览，
 *   就有可能遇到"只提供单个 HTML、不提供同级目录资源"的环境。单文件版在任何
 *   环境下都能打开，避免出现"功能本身没问题、只是资源取不到"的假故障。
 *
 * 它不是主入口：主入口仍是 index.html（源码结构清晰、可读、可分文件维护）。
 * 单文件版是派生产物 —— 改完源码重新跑一次本脚本即可。
 *
 * 用法：
 *   node build-standalone.js          生成（覆盖）
 *   node build-standalone.js --check  只检查是否过期，不写文件（过期则退出码 1）
 * ========================================================================== */
'use strict';

var fs = require('fs');
var path = require('path');

var ROOT = __dirname;
var SRC = path.join(ROOT, 'index.html');
var OUT = path.join(ROOT, 'index-standalone.html');
var MARK = '<!-- generated by build-standalone.js -->';

function build() {
  var html = fs.readFileSync(SRC, 'utf8');
  var inlined = 0;
  var missing = [];
  var imgBytes = 0;

  /* 首页背景照片的地址是运行时拼出来的（app.js 里 'url("' + hero.file + '")'），
     下面那条静态 url() 正则抓不到它。所以单独在 data/photos.js 里把 hero.file
     换成 data URI —— 换完之后 app.js 拼出来的地址本身就是自包含的。
     不做这一步的话，单文件版的背景会静默消失：页面不报错、也不空白，
     只是退回成没有照片的样子，最难发现。 */
  function inlineHero(code) {
    var re = /hero\s*:\s*\{[\s\S]{0,500}?file\s*:\s*['"]([^'"]+\.(?:jpe?g|png|webp|avif|gif))['"]/gi;
    var m, pick = null;
    while ((m = re.exec(code))) {
      /* 文件头的注释里有一段结构一模一样的示例（hero: { file: 'img/hero.jpg' …），
         只认「这个文件真的存在」的那一处；有多处时取最后一处 —— 真正的登记
         写在注释之后。认错地方的话，替换会落在注释里，运行时读到的仍是相对路径，
         单文件版就静默没有背景。 */
      if (fs.existsSync(path.join(ROOT, m[1]))) pick = m;
    }
    if (!pick) return code;
    var abs = path.join(ROOT, pick[1]);
    var ext = path.extname(pick[1]).slice(1).toLowerCase();
    var mime = ext === 'jpg' ? 'jpeg' : ext === 'svg' ? 'svg+xml' : ext;
    var buf = fs.readFileSync(abs);
    imgBytes += buf.length;
    var uri = 'data:image/' + mime + ';base64,' + buf.toString('base64');
    /* 只换这一处。不能在全文里 split —— 注释里的示例也会被换掉，单文件版凭空胖一倍。 */
    return code.replace(pick[0], pick[0].replace(pick[1], uri));
  }

  var out = html.replace(/<script\s+src="([^"]+)"\s*><\/script>/g, function (whole, rel) {
    var abs = path.join(ROOT, rel);
    if (!fs.existsSync(abs)) { missing.push(rel); return whole; }
    var code = fs.readFileSync(abs, 'utf8');
    /* 内联脚本里若出现 "</script>" 字面量会提前闭合标签，必须打断 */
    code = code.replace(/<\/script>/gi, '<\\/script>');
    if (/data[\\/]photos\.js$/i.test(rel)) code = inlineHero(code);
    inlined++;
    return '<script>\n/* ===== inlined: ' + rel + ' ===== */\n' + code + '\n</script>';
  });

  if (missing.length) {
    throw new Error('以下资源不存在，无法内联：' + missing.join(', '));
  }

  /* 样式里指向本地图片的 url("img/hero.jpg") 也一并内联成 base64。
     不内联的话，单文件版会出现「照片层在、文件取不到」——这种失败最难发现：
     页面不报错、也不空白，只是悄悄退回到没有照片的样子。
     只处理带图片后缀的本地路径：url(#mvClip) 这类 SVG 内部引用不会被碰到。 */
  var imgInlined = 0;
  out = out.replace(/url\((['"]?)([^)'"]+?\.(?:jpe?g|png|webp|avif|gif))\1\)/gi,
    function (whole, q, rel) {
      if (/^(?:https?:|data:|\/\/)/i.test(rel)) return whole;
      var abs = path.join(ROOT, rel);
      if (!fs.existsSync(abs)) return whole;      // 没有这张图就保持原样，交给浏览器 404
      var ext = path.extname(rel).slice(1).toLowerCase();
      var mime = ext === 'jpg' ? 'jpeg' : ext === 'svg' ? 'svg+xml' : ext;
      var buf = fs.readFileSync(abs);
      imgInlined++;
      imgBytes += buf.length;
      return 'url("data:image/' + mime + ';base64,' + buf.toString('base64') + '")';
    });

  out = out.replace(/<head(\s[^>]*)?>/i, function (m) { return m + '\n' + MARK; });

  return { html: out, inlined: inlined, imgInlined: imgInlined, imgBytes: imgBytes };
}

var res = build();
var label = '内联脚本 ' + res.inlined + ' 个' +
  (res.imgInlined ? '、图片 ' + res.imgInlined + ' 张（' + Math.round(res.imgBytes / 1024) + ' KB）' : '') +
  '，产出 ' + Math.round(Buffer.byteLength(res.html, 'utf8') / 1024) + ' KB';

if (process.argv.indexOf('--check') >= 0) {
  if (!fs.existsSync(OUT)) {
    console.log('单文件版不存在，请运行 node build-standalone.js');
    process.exit(1);
  }
  var cur = fs.readFileSync(OUT, 'utf8');
  if (cur === res.html) {
    console.log('单文件版是最新的（' + label + '）');
    process.exit(0);
  }
  console.log('单文件版已过期：源码改过但没重新打包，请运行 node build-standalone.js');
  process.exit(1);
}

fs.writeFileSync(OUT, res.html, 'utf8');
console.log('已生成 index-standalone.html（' + label + '）');
