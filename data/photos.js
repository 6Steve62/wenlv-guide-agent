/* ============================================================================
 * 照片素材清单（可选层） —— data/photos.js
 * ----------------------------------------------------------------------------
 * 与 data/ 下其他文件的思路一致：一份**不绑定城市的索引**，按景点 id 与
 * data/yinchuan.js 里的景点关联。界面只查表，不判断照片的含义。
 *
 * 【它是可选的】
 *   查不到某处景点的照片时，界面自动回退到 data/cats.js 的品类插画。
 *   所以这份清单可以是空的、可以只填一部分，页面永远能正常渲染。
 *   找不到 CC0／公有领域素材的点位，保持插画即可，不需要改任何代码。
 *
 * 【授权口径：只收 CC0 与公有领域】
 *   - 两者都无署名义务，且允许任意裁剪与修改，所以结果页缩略图那套
 *     「按 id 错开取景」可以照用。
 *   - 被排除的是 CC BY 与 CC BY-SA：BY 有署名义务；SA 还要求"改编作品同协议
 *     分发"，而裁剪、调色都算改编 —— 会给页面加一层长期约束。
 *   - 注意：维基共享资源上大量景区照片是 CC BY-SA，逐张都要看清协议，
 *     不能因为是"维基的图"就当成公有领域。
 *
 * 【自己拍的照片怎么填】
 *   拍摄者就是本人时，权利完全归自己，不存在授权链问题：
 *     author  填本人姓名（署不署名是展示选择，但清单必须留档）；
 *     license 填 'PD-self'（本人主动释出公有领域）或 'CC0'（放弃全部权利），
 *             两者都在 licenseWhitelist 里，且都不给页面加署名义务；
 *     source  填 'self:' 开头的一句话自证，例如 'self:2026-10 摄于银川贺兰山滚钟口'。
 *             网络图片要求 https 原始页面，自摄照片没有这个地址，用 self: 自证；
 *             test/credits.js 与 CREDITS.md 都认这个前缀。
 *   注意只填自己确实拥有权利的照片：翻拍他人作品、网图另存都不算"自己拍的"。
 *
 * 【加一条的步骤】
 *   1. 把图片存进 img/ 目录，文件名用「景点id-序号」，例如 img/xxl-1.jpg；
 *   2. 在下面的 items 里加一条（字段说明见模板）；
 *   3. 跑 `node test/credits.js` —— 它会核对协议是否在白名单内、图片文件是否
 *      真的存在、id 是否对应到真实景点、来源链接是否填了、有没有孤儿图片。
 *
 * 【模板】
 *   { id: 'xxl',                    // 必须与 data/yinchuan.js 里的景点 id 一致
 *     file: 'img/xxl-1.jpg',        // 相对项目根目录的路径
 *     w: 1600, h: 1000,             // 像素尺寸，用于版面预留，避免加载时跳动
 *     subject: '西夏陵三号陵',       // 这张拍的是什么（同一景点可以有多张）
 *     author: 'BabelStone',         // 拍摄者。CC0／公有领域不强制署名，但必须留档
 *     license: 'CC0',               // 取值见 licenseWhitelist
 *     source: 'https://...',        // 原始页面地址，必须填，答辩时要能当场调出来
 *     fetched: '2026-10-16',        // 获取日期
 *     modified: false,              // 是否做过裁剪／调色／压缩
 *     gps: [105.9908, 38.4361] }    // 可选：照片 EXIF 里的 GPS，已换算成 GCJ-02。
 *                                   // 填了它，test/credits.js 会与数据包坐标做比对
 * ========================================================================= */
window.PHOTOS = {
  version: 1,

  /* 允许收录的授权标识。test/credits.js 逐条核对，前缀匹配
     （所以 'PD-old-70'、'PD-old-100' 都能通过 'PD-old' 这一项）。 */
  licenseWhitelist: [
    'CC0',
    'Public domain',
    'PD-self',
    'PD-old',
    'PD-China'
  ],

  /* 照片拍摄点与景点坐标的容忍距离（米）。超过就报警：
     "这张照片离这处景点太远，可能拍的不是它"。
     参照值：西夏陵三号陵的照片与数据包里的景区代表点相距 937 米 —— 西夏陵
     遗址区南北约 10 公里、东西约 5 公里，三号陵在景区中部，这属于正常范围。 */
  gpsTolerance: 8000,

  /* 目前为空 —— 待补入已确认可用的 CC0／公有领域素材。
     空清单是合法状态：界面会全部走品类插画，与加入此文件之前完全一致。 */
  items: [],

  /* 首页背景照片（可选，独立于 items —— 它不属于任何一处景点）。
     null = 不启用，首页只有自绘的山河底图，与未加此字段时完全一致。
     填上就启用：照片会以 11% 不透明度压在山河底图之上（见 index.html 的 .bg-photo）。
     字段与 items 同一套，缺一不可，test/credits.js 会用同一份白名单核对：

       hero: {
         file: 'img/hero.jpg',            // 实际存放路径，文件名固定用 hero
         subject: '贺兰山晨雾（远景）',      // 拍的是什么 —— 写清楚，别写成「风景」
         author: '某某',                   // 拍摄者。CC0 不强制署名，但必须留档
         license: 'CC0',                  // 只能在 licenseWhitelist 里
         source: 'https://...',           // 原始页面，答辩时要能当场调出来；
                                           // 自己拍的照片填 'self:拍摄说明' 自证，没有网址
         fetched: '2026-10-17',           // 获取日期
         modified: true                   // 是否裁过／压过（背景图基本都要压，一般填 true）
       }

     取图口径见 CREDITS.md：只收 CC0 与公有领域。Unsplash／Pexels／Pixabay
     那类平台自定许可、以及各级文旅部门网站上的宣传图，都不在收录范围内 ——
     前者不保证上传者拥有版权，后者通常只授了「一次性使用权」，无法再转授。 */
  hero: null
};
